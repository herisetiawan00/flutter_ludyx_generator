import 'dart:async';
import 'dart:convert';

import 'package:build/build.dart';
import 'package:glob/glob.dart';

class LudyxLuaBuilder implements Builder {
  final String outputPath;

  LudyxLuaBuilder({this.outputPath = 'assets/lua/components.lua'});

  @override
  Map<String, List<String>> get buildExtensions => {
    r'$package$': [outputPath],
  };

  @override
  Future<void> build(BuildStep buildStep) async {
    final cacheAssets = buildStep.findAssets(Glob('lib/**.ludyx_cache.json'));
    final allComponents = <dynamic>[];

    await for (final assetId in cacheAssets) {
      final rawJson = await buildStep.readAsString(assetId);
      final decoded = jsonDecode(rawJson) as List<dynamic>;
      allComponents.addAll(decoded.cast<dynamic>());
    }

    if (allComponents.isEmpty) {
      return;
    }

    allComponents.sort((a, b) {
      final nameA = a['componentName'] as String;
      final nameB = b['componentName'] as String;
      return nameA.compareTo(nameB);
    });

    final buffer = StringBuffer()
      ..writeln('-- GENERATED CODE - DO NOT MODIFY BY HAND')
      ..writeln('-- Generated by flutter_ludyx_generator')
      ..writeln()
      ..writeln('---@class Component')
      ..writeln('---@diagnostic disable-next-line: duplicate-doc-field')
      ..writeln('---@field component string')
      ..writeln()
      ..writeln('local UI = {}')
      ..writeln();

    final Map<String, List<String>> foundEnum = {};
    final classBuffer = StringBuffer();

    for (final component in allComponents) {
      final params = component['params'];

      for (final param in params) {
        if (param['isEnum'] != true) continue;
        final type = (param['type'] as String).replaceAll('?', '');
        if (foundEnum.containsKey(type)) continue;

        foundEnum[type] = List<String>.from(param['enumValues']);
      }

      generateComponentClass(classBuffer, component);
      classBuffer.writeln();
    }

    for (final MapEntry(:key, :value) in foundEnum.entries) {
      buffer.writeln('---@alias $key ${value.map((v) => '"$v"').join(' | ')}');
      buffer.writeln();
    }

    buffer.write(classBuffer);
    buffer.writeln();

    buffer.writeln('return UI');

    final outputId = AssetId(buildStep.inputId.package, outputPath);
    await buildStep.writeAsString(outputId, buffer.toString());
  }

  void generateComponentClass(StringBuffer buffer, dynamic component) {
    buffer.writeln('---@class ${component['className']}Props');
    for (final param in component['params']) {
      final nullable = (param['type'] as String).endsWith('?');
      final type = dartTypeToLua(param['type']);

      buffer.writeln('---@field ${param['name']}${nullable ? '?' : ''} $type');
    }

    buffer
      ..writeln()
      ..writeln(
        '---@class ${component['className']}: Component, ${component['className']}Props',
      )
      ..writeln('---@field component "${component['componentName']}"')
      ..writeln()
      ..writeln('---@param props ${component['className']}Props')
      ..writeln('---@return ${component['className']}')
      ..writeln('function UI.${component['className']}(props)')
      ..writeln('  ---@cast props ${component['className']}')
      ..writeln('  props.component = "${component['componentName']}"')
      ..writeln('  return props')
      ..writeln('end');
  }

  String dartTypeToLua(String dartType) {
    final raw = dartType.trim();
    if (raw.isEmpty) return 'any';

    // 1. Handle top-level nullable suffix '?' (careful not to strip '?' inside Function(...))
    if (_hasTopLevelNullableSuffix(raw)) {
      final nonNull = raw.substring(0, raw.length - 1).trim();
      final innerLua = dartTypeToLua(nonNull);
      // Wrap function types in parentheses before adding '?' for valid LuaLS syntax
      if (nonNull.contains('Function(')) {
        return '($innerLua)?';
      }
      return '$innerLua?';
    }

    // 2. Handle Function types: e.g. "void Function(String, int)" -> "fun(arg1: string, arg2: number): nil"
    final fnMatch = _matchTopLevelFunction(raw);
    if (fnMatch != null) {
      final returnTypeStr = fnMatch.returnType;
      final paramsStr = fnMatch.params;

      final luaReturn = dartTypeToLua(returnTypeStr);

      if (paramsStr.trim().isEmpty) {
        return 'fun(): $luaReturn';
      }

      final rawParams = _splitTopLevelArgs(paramsStr);
      final luaParams = <String>[];

      for (var i = 0; i < rawParams.length; i++) {
        var param = rawParams[i].trim();
        if (param.isEmpty) continue;

        // Strip optional positional brackets [...] or named braces {...}
        final isOptionalGroup =
            (param.startsWith('[') && param.endsWith(']')) ||
            (param.startsWith('{') && param.endsWith('}'));
        if (isOptionalGroup) {
          param = param.substring(1, param.length - 1).trim();
          // If multiple parameters were inside [...] or {...}, split and process them
          final innerGroupParams = _splitTopLevelArgs(param);
          for (var j = 0; j < innerGroupParams.length; j++) {
            luaParams.add(
              _formatLuaFnParam(
                innerGroupParams[j],
                luaParams.length + 1,
                forceOptional: true,
              ),
            );
          }
          continue;
        }

        luaParams.add(_formatLuaFnParam(param, luaParams.length + 1));
      }

      return 'fun(${luaParams.join(', ')}): $luaReturn';
    }

    // 3. Handle Generics: List<T>, Set<T>, Iterable<T>, Map<K, V>, Future<T>
    final genericStart = raw.indexOf('<');
    if (genericStart != -1 && raw.endsWith('>')) {
      final base = raw.substring(0, genericStart).trim();
      final inner = raw.substring(genericStart + 1, raw.length - 1).trim();
      final args = _splitTopLevelArgs(inner);

      switch (base) {
        case 'List':
        case 'Set':
        case 'Iterable':
          final itemType = args.isNotEmpty ? dartTypeToLua(args[0]) : 'any';
          return '$itemType[]';
        case 'Map':
          final keyType = args.isNotEmpty ? dartTypeToLua(args[0]) : 'any';
          final valType = args.length > 1 ? dartTypeToLua(args[1]) : 'any';
          return 'table<$keyType, $valType>';
        case 'Future':
        case 'FutureOr':
          return args.isNotEmpty ? dartTypeToLua(args[0]) : 'any';
      }
    }

    // 4. Primitive & Core Dart Types
    return switch (raw) {
      'String' => 'string',
      'int' => 'integer',
      'double' || 'num' => 'number',
      'bool' => 'boolean',
      'void' || 'Null' || 'null' => 'nil',
      'dynamic' || 'Object' => 'any',
      'Map' || 'List' || 'Set' => 'table',
      'Widget' => 'Component',
      _ => raw,
    };
  }

  String _formatLuaFnParam(
    String rawParam,
    int index, {
    bool forceOptional = false,
  }) {
    var p = rawParam.trim();
    var isRequired = false;

    if (p.startsWith('required ')) {
      isRequired = true;
      p = p.substring('required '.length).trim();
    }

    final split = _splitTypeAndName(p);
    final luaType = dartTypeToLua(split.type);
    final paramName = split.name ?? 'arg$index';

    final shouldBeOptional =
        forceOptional && !isRequired && !luaType.endsWith('?');
    final optSuffix = shouldBeOptional ? '?' : '';

    return '$paramName$optSuffix: $luaType';
  }

  ({String type, String? name}) _splitTypeAndName(String param) {
    var depthAngle = 0;
    var depthParen = 0;
    var lastSpaceIndex = -1;

    for (var i = 0; i < param.length; i++) {
      final ch = param[i];
      if (ch == '<') depthAngle++;
      if (ch == '>') depthAngle--;
      if (ch == '(') depthParen++;
      if (ch == ')') depthParen--;
      if (ch == ' ' && depthAngle == 0 && depthParen == 0) {
        lastSpaceIndex = i;
      }
    }

    if (lastSpaceIndex == -1) {
      return (type: param, name: null);
    }

    final left = param.substring(0, lastSpaceIndex).trim();
    final right = param.substring(lastSpaceIndex + 1).trim();

    if (right.startsWith('Function(') ||
        right.endsWith('>') ||
        right.endsWith(')')) {
      return (type: param, name: null);
    }

    return (type: left, name: right);
  }

  bool _hasTopLevelNullableSuffix(String type) {
    if (!type.endsWith('?')) return false;
    var depthAngle = 0;
    var depthParen = 0;
    for (var i = 0; i < type.length - 1; i++) {
      final ch = type[i];
      if (ch == '<') depthAngle++;
      if (ch == '>') depthAngle--;
      if (ch == '(') depthParen++;
      if (ch == ')') depthParen--;
    }
    return depthAngle == 0 && depthParen == 0;
  }

  ({String returnType, String params})? _matchTopLevelFunction(String type) {
    var depthAngle = 0;
    var depthParen = 0;

    for (var i = 0; i < type.length; i++) {
      final ch = type[i];
      if (ch == '<') depthAngle++;
      if (ch == '>') depthAngle--;
      if (ch == '(') depthParen++;
      if (ch == ')') depthParen--;

      if (depthAngle == 0 &&
          depthParen == 0 &&
          type.startsWith('Function(', i)) {
        final returnType = type.substring(0, i).trim();
        final openParen = i + 'Function'.length;
        if (type.endsWith(')')) {
          final params = type.substring(openParen + 1, type.length - 1);
          return (returnType: returnType, params: params);
        }
      }
    }
    return null;
  }

  List<String> _splitTopLevelArgs(String input) {
    final result = <String>[];
    var depthAngle = 0;
    var depthParen = 0;
    var depthBracket = 0;
    var depthBrace = 0;
    var start = 0;

    for (var i = 0; i < input.length; i++) {
      switch (input[i]) {
        case '<':
          depthAngle++;
        case '>':
          depthAngle--;
        case '(':
          depthParen++;
        case ')':
          depthParen--;
        case '[':
          depthBracket++;
        case ']':
          depthBracket--;
        case '{':
          depthBrace++;
        case '}':
          depthBrace--;
        case ',':
          if (depthAngle == 0 &&
              depthParen == 0 &&
              depthBracket == 0 &&
              depthBrace == 0) {
            result.add(input.substring(start, i).trim());
            start = i + 1;
          }
      }
    }

    final tail = input.substring(start).trim();
    if (tail.isNotEmpty) result.add(tail);
    return result;
  }
}
